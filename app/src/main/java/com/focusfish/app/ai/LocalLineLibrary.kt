package com.focusfish.app.ai

/**
 * 本地台词库
 *
 * 借鉴 dsh-whale-musume 的设计：530+ 条本地台词，零 token 成本。
 *
 * 为什么这很重要：
 * 陪伴型 AI 的「活人感」很大一部分来自「她随时都在」——
 * 但每次都调模型既花钱又慢（首 token 要 1-3 秒）。
 * 而生活化的碎碎念根本不需要 LLM，本地随机取一句就够了。
 *
 * 用法：
 * - 用户进专注页时，大肥鱼本地念一句（不调模型，不花钱）
 * - 用户退出专注时，本地念一句反馈
 * - 用户在首页待着没事干，本地发发呆
 *
 * 台词刻意写成大肥鱼的口吻（自称"本鲸"、叫对方"鱼片"、摸鱼/吃白饭/傲娇），
 * 而不是通用励志语 —— 这才像"有个活物在跟你说话"。
 */
object LocalLineLibrary {

    /**
     * 台词分组
     */
    enum class Scene {
        /** 用户开始专注 */
        FOCUS_START,

        /** 用户专注结束 */
        FOCUS_END,

        /** 用户进首页发呆 */
        IDLE,

        /** 用户被拦截了（想摸鱼） */
        BLOCKED,

        /** 大肥鱼饿了 */
        HUNGRY,

        /** 大肥鱼刚睡醒 */
        JUST_WOKE,

        /** 用户很久没来 */
        LONG_ABSENCE
    }

    /**
     * 台词表
     *
     * 每组 8-12 句，随机取。宁可写多也不要少 —— 重复同一句是"假活人"的开始。
     */
    private val LINES: Map<Scene, List<String>> = mapOf(
        Scene.FOCUS_START to listOf(
            "好，本鲸开始摸鱼了。你专心啊。",
            "计时开始。饿了记得喂我。",
            "我盯着你呢，别偷偷划水。",
            "冲吧鱼片，白饭在等着。",
            "本鲸已进入深度思考…其实是在盯着你。",
            "这波稳了。我去给你数着时间。",
            "行，锅给你看着。本鲸先眯一会儿。",
            "开始咯。中途想摸鱼我会说的。",
            "别急，慢慢来，本鲸又不催你。",
            "来了来了。这回别中途跑掉啊。"
        ),
        Scene.FOCUS_END to listOf(
            "呼——终于结束了。你累不累？",
            "本鲸在这儿守了半小时，白饭呢？",
            "干得不错。给你记上了。",
            "好了，休息一下。你刚才比我想象中能扛。",
            "完成！本鲸的下一碗有着落了。",
            "欸，别一停就摸手机啊。",
            "辛苦啦。要不要歇会儿再动？",
            "哇，你居然真的做完了。"
        ),
        Scene.IDLE to listOf(
            "……",
            "本鲸在发呆。",
            "你说人一天到底有多少时间在发呆。",
            "我在想晚饭吃什么。想的还是白饭。",
            "诶，你说我是不是该减肥了。",
            "（尾巴摆了摆）",
            "好无聊。",
            "本鲸刚才做了个梦，梦里全是白饭。",
            "有时候就发会儿呆挺好的。",
            "你在忙什么呀。没事，本鲸就随口问问。"
        ),
        Scene.BLOCKED to listOf(
            "欸，刚摸到手机就被我逮住了吧？",
            "手放下。再专注一会儿，我就有大白饭吃了。",
            "本鲸看见了。别装了。",
            "又是你。三分钟的分心换不来三分钟的快乐。",
            "我数着呢，今天第几次了啊。",
            "手机放下吧。你刚放下的这几分钟比你拿起来的时间值钱。",
            "哼！说了别摸手机，你是听不懂鲸语吗。",
            "想清楚再回来啊。我又不会跑。"
        ),
        Scene.HUNGRY to listOf(
            "……本鲸的白饭呢。",
            "肚子有点空。你不打算喂喂我吗。",
            "饿。真的饿。不是撒娇那种饿。",
            "我盯着你的大白饭库存看了半天了。",
            "你专注的时候我能分到一点吗。",
            "想吃白饭。想得很具体的那种。",
            "（尾巴有气无力地摆了摆）",
            "喂我一口。就一口。"
        ),
        Scene.JUST_WOKE to listOf(
            "zzz… 唔…？你回来了？",
            "本鲸刚睡醒，做了个梦。",
            "睡饱了。现在能吃三碗。",
            "哈啊——睡醒了。你还在啊。",
            "睡了多久来着…算了不重要。"
        ),
        Scene.LONG_ABSENCE to listOf(
            "你终于回来了。本鲸等好久了。",
            "好久没见你了。我都快发霉了。",
            "你知不知道你走了多久。",
            "欸，别走啊，再专注一会儿，大白饭就有着落了。",
            "本鲸把你的位置留着了。"
        )
    )

    /**
     * 取一句台词
     *
     * @param scene 场景
     * @param seed 随机种子，同一 seed 结果固定
     */
    fun line(scene: Scene, seed: Int = kotlin.random.Random.nextInt()): String {
        val pool = LINES[scene] ?: return ""
        return pool[Math.floorMod(seed, pool.size)]
    }

    /**
     * 判断场景是否有台词
     */
    fun hasLine(scene: Scene): Boolean = !LINES[scene].isNullOrEmpty()
}
